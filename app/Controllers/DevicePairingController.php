<?php

namespace App\Controllers;

use App\Services\DevicePairingService;

helper('token');
helper('user');

/**
 * Desktop device linking.
 *
 * Routes are added to the existing `user` group, so the mobile app's existing
 * user routes are untouched. Nothing here replaces the phone OTP flow — this is
 * strictly an additional way for a second, desktop-class device to obtain a
 * session for an account that a phone has already approved.
 *
 * Three of these endpoints are deliberately unauthenticated (the desktop has no
 * session yet, that is the entire point): createPairing, getPairingStatus and
 * claimPairing. They are safe without a JWT because none of them can mint a
 * session on their own — see DevicePairingService for why. approvePairing and
 * everything under linked-devices require a valid phone JWT.
 */
class DevicePairingController extends BaseController
{
    /**
     * Test hook: force the IP rate limiter on even under ENVIRONMENT=testing so
     * the limiter wiring can be exercised end to end. Off everywhere else.
     */
    public static bool $enforceRateLimit = false;

    private function pairing(): DevicePairingService
    {
        return new DevicePairingService();
    }

    /** Resolve the caller, or null. Also enforces device revocation. */
    private function caller(): ?object
    {
        $jwt = check_jwt_authentication();
        if (! $jwt) {
            return null;
        }

        $userId = $jwt->user_id ?? null;
        if ($userId === null) {
            return null;
        }

        // A revoked desktop token is dead immediately, not just hidden from the
        // linked-devices list.
        if (! $this->pairing()->assertDeviceActive((int) $userId, $jwt->device_id ?? null)) {
            return null;
        }

        return $jwt;
    }

    private function deviceIdFromRequest(): ?int
    {
        $id = $this->request->getVar('device_id');

        return is_numeric($id) ? (int) $id : null;
    }

    /**
     * Best-effort per-IP rate limit for the unauthenticated pairing actions.
     *
     * These are the only routes reachable before a caller holds a session, so
     * they are the ones worth metering. Skipped under the testing environment:
     * the feature suite makes dozens of pairing calls from one address and would
     * otherwise test the limiter instead of the flow. The limiter itself is
     * covered directly by a unit test.
     *
     * @return bool true when the request should be refused with 429
     */
    private function throttled(string $bucket, int $capacity, int $seconds): bool
    {
        if (! self::$enforceRateLimit && defined('ENVIRONMENT') && ENVIRONMENT === 'testing') {
            return false;
        }

        return ! $this->pairing()->allowRequest(
            $bucket,
            (string) $this->request->getIPAddress(),
            $capacity,
            $seconds,
        );
    }

    private function tooManyRequests()
    {
        return $this->response->setStatusCode(429)->setJSON([
            'status'  => false,
            'message' => 'Too many requests. Please wait a moment and try again.',
        ]);
    }

    // ------------------------------------------------------- desktop: no JWT

    /**
     * POST /user/desktop-pairing/create
     *
     * The desktop opens a 60 second window and gets back the two public values
     * that go into the QR code. `claim_secret` is generated by the desktop
     * itself and is stored only as a hash. No credential is involved.
     */
    public function createPairing()
    {
        // 30 new sessions per minute per address is far above real usage — a
        // person pairs once — but caps a script opening sessions in a loop.
        if ($this->throttled('create', 30, 60)) {
            return $this->tooManyRequests();
        }

        try {
            $result = $this->pairing()->createPairingSession([
                'device_name'  => $this->request->getVar('device_name'),
                'platform'     => $this->request->getVar('platform'),
                'browser'      => $this->request->getVar('browser'),
                'app_version'  => $this->request->getVar('app_version'),
                'claim_secret' => $this->request->getVar('claim_secret'),
            ]);

            if (isset($result['error'])) {
                return $this->response->setStatusCode(500)->setJSON([
                    'status'  => false,
                    'message' => $result['error'],
                ]);
            }

            return $this->response->setJSON([
                'status'  => true,
                'message' => 'Pairing session created',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'createPairing: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /**
     * GET /user/desktop-pairing/status?pairing_ref=...
     *
     * Always resolves to a terminal state, including expiry, so a desktop
     * never has to poll forever. Safe to call without a JWT: it only reports
     * state for a pairing_ref the caller itself generated.
     */
    public function getPairingStatus()
    {
        // The desktop legitimately polls this every 1.5s while a QR is live
        // (~40/min), so the budget is set well above that to leave headroom for
        // several windows at once while still capping a hammering client.
        if ($this->throttled('status', 240, 60)) {
            return $this->tooManyRequests();
        }

        try {
            $ref = (string) $this->request->getVar('pairing_ref');
            $data = $this->pairing()->getPairingStatus($ref);

            return $this->response->setJSON([
                'status'  => true,
                'message' => 'Pairing status',
                'data'    => $data,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'getPairingStatus: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /**
     * POST /user/desktop-pairing/claim
     *
     * Redeem the claim secret for a desktop session token. This is the only
     * place a desktop token is ever issued.
     */
    public function claimPairing()
    {
        // A real desktop claims exactly once. This caps a caller that replays a
        // stolen QR's public values against the challenge/secret check.
        if ($this->throttled('claim', 30, 60)) {
            return $this->tooManyRequests();
        }

        try {
            $result = $this->pairing()->claimPairing(
                (string) $this->request->getVar('pairing_ref'),
                (string) $this->request->getVar('claim_secret'),
                (string) $this->request->getVar('challenge'),
            );

            if (($result['status'] ?? '') === 'connected') {
                return $this->response->setJSON([
                    'status'  => true,
                    'message' => 'Device linked',
                    'data'    => $result,
                ]);
            }

            $expired = in_array($result['status'] ?? '', ['expired', 'consumed'], true);

            return $this->response->setStatusCode($expired ? 410 : 400)->setJSON([
                'status'  => false,
                'message' => 'Could not link this device',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'claimPairing: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    // --------------------------------------------------------- phone: JWT

    /**
     * POST /user/desktop-pairing/approve
     *
     * The phone confirms the scanned QR. Requires a valid JWT, and the session
     * must still be unowned and unexpired.
     */
    public function approvePairing()
    {
        // `caller()` (not a raw check) is required: the temp token minted by
        // `register-number` has no `user_id` claim, and casting a missing claim
        // to int yields 0. Approving with 0 would create an orphan `user_id=0`
        // device and hand back a desktop JWT for a phantom account. `caller()`
        // rejects any token without a real `user_id`.
        $jwt = $this->caller();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $result = $this->pairing()->approvePairing(
                (int) $jwt->user_id,
                (string) $this->request->getVar('pairing_ref'),
                (string) $this->request->getVar('challenge'),
            );

            if (($result['status'] ?? '') === 'approved') {
                return $this->response->setJSON([
                    'status'  => true,
                    'message' => 'Device approved',
                    'data'    => $result,
                ]);
            }

            return $this->response->setStatusCode(400)->setJSON([
                'status'  => false,
                'message' => 'Could not approve this device',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'approvePairing: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /** POST /user/desktop-pairing/reject */
    public function rejectPairing()
    {
        // Same requirement as approvePairing: a real phone session, not just the
        // OTP temp token (which carries no user_id). Keeps an unauthenticated
        // caller from cancelling a pairing they merely scanned.
        $jwt = $this->caller();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $result = $this->pairing()->rejectPairing((string) $this->request->getVar('pairing_ref'));

            return $this->response->setJSON([
                'status'  => true,
                'message' => 'Device rejected',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'rejectPairing: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    // ------------------------------------------------------- linked devices

    /** GET /user/linked-devices */
    public function listDevices()
    {
        $jwt = $this->caller();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            return $this->response->setJSON([
                'status'  => true,
                'message' => 'Linked devices',
                'data'    => $this->pairing()->listDevices((int) $jwt->user_id),
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'listDevices: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /**
     * POST /user/linked-devices/revoke
     *
     * body: device_id | all_others=1
     */
    public function revokeDevice()
    {
        $jwt = $this->caller();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $service = $this->pairing();
            $userId  = (int) $jwt->user_id;

            if ((string) $this->request->getVar('all_others') === '1') {
                $result = $service->revokeAllOtherDevices($userId, (int) ($jwt->device_id ?? 0));
            } else {
                $deviceId = $this->deviceIdFromRequest();
                if ($deviceId === null) {
                    return $this->response->setStatusCode(400)->setJSON(['status' => false, 'message' => 'device_id is required']);
                }
                $result = $service->revokeDevice($userId, $deviceId, (int) ($jwt->device_id ?? 0));
            }

            if (($result['status'] ?? '') === 'ok') {
                return $this->response->setJSON([
                    'status'  => true,
                    'message' => 'Device revoked',
                    'data'    => $result,
                ]);
            }

            $conflict = ($result['reason'] ?? '') === 'cannot_revoke_current_device';

            return $this->response->setStatusCode($conflict ? 409 : 400)->setJSON([
                'status'  => false,
                'message' => $conflict ? 'Use logout to sign out of this device' : 'Could not revoke this device',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'revokeDevice: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /** POST /user/linked-devices/rename */
    public function renameDevice()
    {
        $jwt = $this->caller();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $deviceId = $this->deviceIdFromRequest();
            if ($deviceId === null) {
                return $this->response->setStatusCode(400)->setJSON(['status' => false, 'message' => 'device_id is required']);
            }

            $result = $this->pairing()->renameDevice(
                (int) $jwt->user_id,
                $deviceId,
                (string) $this->request->getVar('device_name'),
            );

            if (($result['status'] ?? '') === 'ok') {
                return $this->response->setJSON([
                    'status'  => true,
                    'message' => 'Device renamed',
                    'data'    => $result,
                ]);
            }

            return $this->response->setStatusCode(400)->setJSON([
                'status'  => false,
                'message' => 'Could not rename this device',
                'data'    => $result,
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'renameDevice: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /**
     * POST /user/linked-devices/logout
     *
     * Revokes the device behind the caller's own token, so a stolen desktop
     * token that logs out leaves the row revoked and unusable.
     */
    public function logoutDevice()
    {
        $jwt = check_jwt_authentication();
        if (! $jwt) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $this->pairing()->revokeFromToken((int) $jwt->user_id, $jwt->device_id ?? null);

            return $this->response->setJSON([
                'status'  => true,
                'message' => 'Signed out',
                'data'    => ['status' => 'ok'],
            ]);
        } catch (\Throwable $e) {
            log_message('error', 'logoutDevice: ' . $e->getMessage());
            return $this->response->setStatusCode(500)->setJSON(['status' => false, 'message' => $e->getMessage()]);
        }
    }

    /**
     * GET /user/device-status?device_id=...
     *
     * Internal (X-Internal-Key) check used by the socket server at handshake: a
     * desktop token stops working the instant the row is revoked, but the socket
     * handshake only verifies the JWT signature - it would otherwise keep
     * accepting a revoked device that reconnects with its still-valid token.
     * Reports only whether the device is active; never returns device details.
     */
    public function deviceStatus()
    {
        $expectedKey = getenv('INTERNAL_CRON_KEY');
        if ($expectedKey === false || $expectedKey === '') {
            log_message('error', 'deviceStatus: INTERNAL_CRON_KEY not set');
            return $this->response->setStatusCode(503)->setJSON(['status' => false, 'message' => 'Device status check is unavailable']);
        }
        $provided = $this->request->getHeaderLine('X-Internal-Key');
        if ($provided === '' || ! hash_equals($expectedKey, $provided)) {
            return $this->response->setStatusCode(401)->setJSON(['status' => false, 'message' => 'Authorization Failed']);
        }

        try {
            $deviceId = $this->deviceIdFromRequest();
            if ($deviceId === null) {
                return $this->response->setStatusCode(400)->setJSON(['status' => false, 'message' => 'device_id is required']);
            }

            $row = (new \App\Models\UserDeviceModel())->find($deviceId);
            $active = $row !== null && ($row['status'] ?? '') === 'active';

            return $this->response->setJSON([
                'status'  => true,
                'message' => $active ? 'active' : 'revoked',
                'data'    => ['active' => $active],
            ]);
        } catch (\Throwable $e) {
            // Fail open on a lookup error: a database blip must not eject every
            // connected desktop. The HTTP layer still enforces revocation.
            log_message('error', 'deviceStatus: ' . $e->getMessage());
            return $this->response->setJSON([
                'status'  => true,
                'message' => 'unknown',
                'data'    => ['active' => true],
            ]);
        }
    }
}

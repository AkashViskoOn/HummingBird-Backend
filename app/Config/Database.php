        'port'        => 3306,
        'foreignKeys' => true,
        'busyTimeout' => 1000,
    ];

    public function __construct()
    {
        parent::__construct();

        // Database credentials come from the environment (set in .env or the
        // process environment). Values are read here so the connection is
        // preserved exactly as before while keeping secrets out of source.
        $this->default['hostname'] = getenv('DB_HOSTNAME') ?: $this->default['hostname'];
        $this->default['username'] = getenv('DB_USERNAME') ?: $this->default['username'];
        $this->default['password'] = getenv('DB_PASSWORD') ?: $this->default['password'];
        $this->default['database'] = getenv('DB_DATABASE') ?: $this->default['database'];
        $this->default['port']     = getenv('DB_PORT') ?: $this->default['port'];

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
}
